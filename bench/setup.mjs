// 为每个配置建一个隔离 DSH_HOME（profiles 里一个 bench 档案 + 补丁 + AGENTS.md）
// 用法：node setup.mjs [--configs c0,c1]
import { spawnSync } from 'node:child_process'
import { mkdirSync, copyFileSync, writeFileSync, rmSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { BENCH, cfg, cleanEnv } from './config.mjs'

const args = process.argv.slice(2)
const only = args.indexOf('--configs') === -1 ? null : args[args.indexOf('--configs') + 1].split(',')
const CONFIGS = JSON.parse(readFileSync(join(BENCH, 'configs.json'), 'utf8'))

for (const [name, spec] of Object.entries(CONFIGS)) {
  if (only && !only.includes(name)) continue
  const home = join(cfg.homeRoot, name)
  mkdirSync(home, { recursive: true })
  copyFileSync(cfg.credentials, join(home, '.credentials.yaml'))

  const profileDir = join(home, 'profiles', cfg.profile)
  if (!existsSync(join(profileDir, 'cordis.yml'))) {
    const r = spawnSync(process.execPath, [cfg.dshBin, '--profile', cfg.profile, '--from-default-profile', 'headless', '--dump-config'], {
      env: cleanEnv(home), encoding: 'utf8',
    })
    if (r.status !== 0) {
      console.error(`[${name}] 建档案失败（检查 dshBin 路径）:\n${r.stderr.slice(0, 600)}`)
      process.exit(1)
    }
  }

  let patch = `# generated by setup.mjs\n- id: agent-default-model\n  config:\n    provider: ${cfg.provider}\n    model: ${cfg.model}\n    reasoningEffort: ${spec.effort ?? cfg.reasoningEffort}\n`
  for (const p of spec.patch ?? []) patch += readFileSync(join(BENCH, 'patches', p), 'utf8')

  writeFileSync(join(profileDir, 'cordis.patch.yml'), patch)

  const agents = join(home, 'AGENTS.md')
  if (spec.policy) copyFileSync(join(BENCH, 'policies', spec.policy), agents)
  else rmSync(agents, { force: true })

  console.log(`${name}: ${home}  policy=${spec.policy ?? '无'}  patch=${(spec.patch ?? ['无']).join(',')}  (${spec.note})`)
}
